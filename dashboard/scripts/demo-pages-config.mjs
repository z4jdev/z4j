/**
 * Cloudflare Pages routing and header files for the demo build.
 *
 * Pages reads _redirects, _headers and 404.html from the top of the deployed
 * directory. It drops a _redirects line it rejects without a word, and
 * `wrangler pages deploy` uploads the file unparsed, so nothing upstream
 * notices a broken rule. These helpers generate the files from the router's
 * route manifest and re-check a finished dist against the same rules.
 * build-demo.mjs explains what went wrong before and why the files look the
 * way they do.
 */
import { Buffer } from "node:buffer";
import { readFile, readdir } from "node:fs/promises";
import { join } from "node:path";

// Pages limits and permitted statuses, as the wrangler metadata generator
// enforces them. Static rules count as static only until the first dynamic
// rule (one with a splat or a placeholder).
export const MAX_STATIC_RULES = 2000;
export const MAX_DYNAMIC_RULES = 100;
export const MAX_LINE_LENGTH = 2000;
const PERMITTED_STATUSES = new Set([200, 301, 302, 303, 307, 308]);

// Every rule rewrites to the SPA shell at "/". Pages turns a rewrite to
// /index.html, or to any .html path, into a 308 redirect.
const REWRITE_TARGET = "/";
const REWRITE_STATUS = 200;

// Top-level files the build writes after Vite has run. They are not in the
// directory listing yet when _redirects is generated, but no rule may hide
// them either.
export const BUILD_WRITTEN_ENTRIES = [
  "404.html",
  "_headers",
  "_redirects",
  "route-manifest.json",
];

export const HTML_CACHE_CONTROL =
  "public, max-age=0, must-revalidate, no-transform";
export const STATIC_CACHE_CONTROL = "public, max-age=31536000, immutable";
export const DEMO_DATA_CACHE_CONTROL = "public, max-age=300";

const REDIRECTS_PREAMBLE = [
  "# Generated by scripts/build-demo.mjs from route-manifest.json.",
  "# Each router path rewrites to the SPA shell at /; anything else is a 404.",
];

// Unreserved URL characters only, so a static segment can never read as a
// Pages placeholder (":name"), a splat ("*") or a field separator.
const SEGMENT = /^[A-Za-z0-9._~-]+$/;

function plainSegments(segments) {
  return segments.every(
    (segment) => SEGMENT.test(segment) && segment !== "." && segment !== "..",
  );
}

// "static" for an exact path, "dynamic" for "<prefix>/*", null otherwise.
function sourceKind(from) {
  if (!from.startsWith("/")) return null;
  const segments = from.slice(1).split("/");
  if (segments.at(-1) === "*") {
    return segments.length > 1 && plainSegments(segments.slice(0, -1))
      ? "dynamic"
      : null;
  }
  return plainSegments(segments) ? "static" : null;
}

/** Every full path listed in the generated router's FileRoutesByFullPath. */
export function extractRouteManifestPaths(routeTreeSource) {
  const routeInterface = routeTreeSource.match(
    /export interface FileRoutesByFullPath \{([\s\S]*?)\n\}/,
  )?.[1];
  if (!routeInterface)
    throw new Error("Missing FileRoutesByFullPath in generated router");
  return [...routeInterface.matchAll(/['"](\/[^'"]*)['"]:/g)].map(
    (match) => match[1],
  );
}

// A router path's segments, without the leading "/" or an index route's
// trailing one, and the index of the first parameter segment (-1 if none).
function routeSegments(path) {
  const trimmed = path.endsWith("/") ? path.slice(0, -1) : path;
  const segments = trimmed.slice(1).split("/");
  return {
    segments,
    dynamicAt: segments.findIndex((segment) => segment.includes("$")),
  };
}

/**
 * The _redirects source that serves one router path, or null for "/", which
 * index.html answers itself. An index route's trailing slash is dropped (the
 * router never emits one). A path is dynamic from its first segment carrying
 * a "$" parameter, and one splat over the static prefix before that segment
 * covers it.
 */
export function ruleSourceForRoute(path) {
  if (typeof path !== "string" || !path.startsWith("/")) {
    throw new Error(`route path must start with "/": ${JSON.stringify(path)}`);
  }
  if (path === "/") return null;
  const { segments, dynamicAt } = routeSegments(path);
  const prefix = dynamicAt === -1 ? segments : segments.slice(0, dynamicAt);
  if (dynamicAt === 0) {
    throw new Error(
      `route ${path} has no static prefix; its rule would be the catch-all "/*"`,
    );
  }
  if (!plainSegments(prefix)) {
    throw new Error(
      `route path has a segment _redirects cannot express: ${JSON.stringify(path)}`,
    );
  }
  return dynamicAt === -1 ? `/${prefix.join("/")}` : `/${prefix.join("/")}/*`;
}

// A segment TanStack Router can match against nothing: an optional parameter
// ("{-$lang}", with or without text around it), which it skips, or a splat
// with nothing around it ("$" or "{$}"), which captures an empty rest.
function mayBeAbsent(segment) {
  return (
    segment === "$" || segment === "{$}" || /^[^{]*\{-\$[^}]+\}/.test(segment)
  );
}

/**
 * The bare static prefix a dynamic route also serves, or null. When every
 * segment from the first parameter on may be absent ("/docs/{-$lang}",
 * "/files/$"), the router answers the prefix itself, which the route's
 * "<prefix>/*" rule does not match, so an exact rule has to cover it.
 */
export function barePrefixOfRoute(path) {
  const source = ruleSourceForRoute(path);
  if (source === null || !source.endsWith("/*")) return null;
  const { segments, dynamicAt } = routeSegments(path);
  return segments.slice(dynamicAt).every(mayBeAbsent)
    ? source.slice(0, -"/*".length)
    : null;
}

/**
 * The top-level dist entry a rule source would hide, or null. Pages applies a
 * matching rule even when a file exists at that path, and serves x.html at
 * /x as well, so no rule may start with an entry name or an HTML stem.
 */
export function shadowedEntry(source, entries) {
  const first = source.slice(1).split("/")[0];
  return (
    entries.find(
      (entry) =>
        entry === first ||
        (entry.endsWith(".html") && entry.slice(0, -".html".length) === first),
    ) ?? null
  );
}

/**
 * The _redirects text for a route manifest: the comment preamble, one exact
 * rule per static path, then one splat per dynamic prefix, each group sorted
 * and deduplicated. Throws instead of writing a rule that is a catch-all,
 * hides a real dist entry, or goes past a Pages limit, and instead of leaving
 * a path the router serves without a rule.
 */
export function buildRedirects(manifestPaths, distEntries) {
  if (!Array.isArray(manifestPaths) || manifestPaths.length === 0) {
    throw new Error("route manifest has no paths");
  }
  const staticSources = new Set();
  const dynamicSources = new Set();
  const barePrefixes = [];
  for (const path of manifestPaths) {
    const source = ruleSourceForRoute(path);
    if (source === null) continue;
    const entry = shadowedEntry(source, distEntries);
    if (entry !== null) {
      throw new Error(
        `route ${path} would rewrite ${source}, hiding the real dist entry ${entry}`,
      );
    }
    (source.endsWith("/*") ? dynamicSources : staticSources).add(source);
    const bare = barePrefixOfRoute(path);
    if (bare !== null) barePrefixes.push({ path, bare });
  }
  for (const { path, bare } of barePrefixes) {
    if (!staticSources.has(bare)) {
      throw new Error(
        `route ${path} also serves ${bare}, which ${bare}/* does not match ` +
          "and no static route covers",
      );
    }
  }
  if (staticSources.size > MAX_STATIC_RULES) {
    throw new Error(
      `${staticSources.size} static rules exceed the Pages limit of ${MAX_STATIC_RULES}`,
    );
  }
  if (dynamicSources.size > MAX_DYNAMIC_RULES) {
    throw new Error(
      `${dynamicSources.size} dynamic rules exceed the Pages limit of ${MAX_DYNAMIC_RULES}`,
    );
  }
  const rule = (source) => `${source} ${REWRITE_TARGET} ${REWRITE_STATUS}`;
  return [
    ...REDIRECTS_PREAMBLE,
    ...[...staticSources].sort().map(rule),
    ...[...dynamicSources].sort().map(rule),
    "",
  ].join("\n");
}

/**
 * The _headers text. The catch-all block comes first: a later, narrower
 * block's "! Cache-Control" removes the value the catch-all set before it
 * states its own, which is how /static/* and /demo-data/* shed no-transform.
 */
export function buildHeaders(csp) {
  if (typeof csp !== "string" || csp.trim() === "" || /[\r\n]/.test(csp)) {
    throw new Error("Content-Security-Policy must be one non-empty line");
  }
  const text = [
    "/*",
    `  Cache-Control: ${HTML_CACHE_CONTROL}`,
    "  X-Frame-Options: DENY",
    "  X-Content-Type-Options: nosniff",
    "  Referrer-Policy: strict-origin-when-cross-origin",
    // The demo is a sample dashboard, not documentation: keep it out of search
    // results so it never outranks the docs for the product's own name.
    // Crawling stays allowed (robots.txt) so crawlers can see this header.
    "  X-Robots-Tag: noindex",
    `  Content-Security-Policy: ${csp}`,
    "",
    "/static/*",
    "  ! Cache-Control",
    `  Cache-Control: ${STATIC_CACHE_CONTROL}`,
    "",
    "/demo-data/*",
    "  ! Cache-Control",
    `  Cache-Control: ${DEMO_DATA_CACHE_CONTROL}`,
    "",
  ].join("\n");
  if (text.split("\n").some((line) => line.length > MAX_LINE_LENGTH)) {
    throw new Error(
      `a _headers line exceeds the Pages limit of ${MAX_LINE_LENGTH} characters`,
    );
  }
  return text;
}

/**
 * Parse _redirects the way Pages does. Returns the rules Pages keeps, in file
 * order, and the lines it ignores with the reason. A rule without a splat or
 * placeholder that comes after a dynamic rule is "demoted": Pages still
 * applies it, but as a dynamic rule.
 */
export function parseRedirects(text) {
  const rules = [];
  const invalid = [];
  const seen = new Set();
  let staticRules = 0;
  let dynamicRules = 0;
  let staticAllowed = true;
  const lines = text.split("\n");
  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index].trim();
    if (line === "" || line.startsWith("#")) continue;
    const ignore = (message) =>
      invalid.push({ lineNumber: index + 1, line, message });
    if (line.length > MAX_LINE_LENGTH) {
      ignore(`it is longer than ${MAX_LINE_LENGTH} characters`);
      continue;
    }
    const tokens = line.split(/\s+/);
    if (tokens.length < 2 || tokens.length > 3) {
      ignore(`it has ${tokens.length} fields, not 2 or 3`);
      continue;
    }
    const [from, to, statusText = "302"] = tokens;
    const dynamic = /\*/.test(from) || /:[A-Za-z]/.test(from);
    const demoted = !dynamic && !staticAllowed;
    if (!dynamic && staticAllowed) {
      staticRules += 1;
      if (staticRules > MAX_STATIC_RULES) {
        ignore(`it passes the limit of ${MAX_STATIC_RULES} static rules`);
        continue;
      }
    } else {
      staticAllowed = false;
      dynamicRules += 1;
      if (dynamicRules > MAX_DYNAMIC_RULES) {
        ignore(
          `it passes the limit of ${MAX_DYNAMIC_RULES} dynamic rules, ` +
            "and so does every line after it",
        );
        break;
      }
    }
    const status = Number(statusText);
    if (!PERMITTED_STATUSES.has(status)) {
      ignore(
        `status ${statusText} is not one of ${[...PERMITTED_STATUSES].join(", ")}`,
      );
      continue;
    }
    if (/\/\*?$/.test(from) && /\/index(\.html)?$/.test(to)) {
      ignore("it would loop, because Pages strips /index.html back to /");
      continue;
    }
    if (seen.has(from)) {
      ignore(`it repeats the source ${from}`);
      continue;
    }
    seen.add(from);
    rules.push({ lineNumber: index + 1, from, to, status, dynamic, demoted });
  }
  return { rules, invalid };
}

// Whether Pages would apply a rule with this source to a request path: "*"
// matches anything, ":name" one segment, and the whole path must match.
function ruleMatches(from, path) {
  const pattern = from
    .split("*")
    .map((part) =>
      part.replace(/[.+?^${}()|[\]\\]/g, "\\$&").replace(/:\w+/g, "[^/]+"),
    )
    .join(".*");
  return new RegExp(`^${pattern}$`).test(path);
}

// A concrete request path for a router path: parameter segments get a sample
// value, and an index route loses its trailing slash.
function samplePath(path) {
  const trimmed = path.endsWith("/") ? path.slice(0, -1) : path;
  return trimmed
    .split("/")
    .map((segment) => (segment.includes("$") ? "sample" : segment))
    .join("/");
}

// Where two texts first differ, as "line N is X, expected Y", or null.
function firstDifference(actual, expected) {
  if (actual === expected) return null;
  const actualLines = actual.split("\n");
  const expectedLines = expected.split("\n");
  const show = (line) => (line === undefined ? "absent" : JSON.stringify(line));
  const length = Math.max(actualLines.length, expectedLines.length);
  for (let index = 0; index < length; index += 1) {
    if (actualLines[index] !== expectedLines[index]) {
      return (
        `line ${index + 1} is ${show(actualLines[index])}, ` +
        `expected ${show(expectedLines[index])}`
      );
    }
  }
  return null;
}

function headersViolations(text, csp) {
  if (text == null) return ["_headers is missing"];
  const policy =
    csp ?? /^ {2}Content-Security-Policy: (.+)$/m.exec(text)?.[1];
  if (!policy) return ["_headers has no Content-Security-Policy"];
  let expected;
  try {
    expected = buildHeaders(policy);
  } catch (error) {
    return [`_headers: ${error.message}`];
  }
  const drift = firstDifference(text, expected);
  return drift === null ? [] : [`_headers ${drift}`];
}

function redirectsViolations(text, manifestPaths, entries) {
  if (text == null) return ["_redirects is missing"];
  const violations = [];
  const { rules, invalid } = parseRedirects(text);
  for (const { lineNumber, line, message } of invalid) {
    violations.push(
      `_redirects line ${lineNumber} ${JSON.stringify(line)}: Pages ignores it, ${message}`,
    );
  }
  for (const { lineNumber, from, to, status, demoted } of rules) {
    const at = `_redirects line ${lineNumber} ${JSON.stringify(`${from} ${to} ${status}`)}`;
    if (from === "/*") {
      violations.push(`${at}: a catch-all "/*" rule is not allowed`);
    } else if (sourceKind(from) === null) {
      violations.push(
        `${at}: the source is neither an exact route path nor "<prefix>/*"`,
      );
    }
    if (demoted) {
      violations.push(
        `${at}: a static rule after a dynamic rule; static rules must come first`,
      );
    }
    if (status !== REWRITE_STATUS) {
      violations.push(`${at}: status ${status}, expected ${REWRITE_STATUS}`);
    }
    if (to !== REWRITE_TARGET) {
      violations.push(
        `${at}: target ${to}, expected "/" (Pages turns .html and /index targets into 308 redirects)`,
      );
    }
    const entry = shadowedEntry(from, entries);
    if (entry !== null) {
      violations.push(`${at}: hides the real dist entry ${entry}`);
    }
  }
  if (manifestPaths === null) return violations;

  // Coverage is judged by what Pages would do: a route is served only when a
  // rule Pages keeps rewrites it to "/" with 200. A route that also serves
  // its bare prefix is checked at that prefix too.
  const rewrites = rules.filter(
    (rule) => rule.status === REWRITE_STATUS && rule.to === REWRITE_TARGET,
  );
  for (const path of manifestPaths) {
    let bare;
    try {
      if (ruleSourceForRoute(path) === null) continue;
      bare = barePrefixOfRoute(path);
    } catch (error) {
      violations.push(`route-manifest.json: ${error.message}`);
      continue;
    }
    const samples = [samplePath(path), ...(bare === null ? [] : [bare])];
    for (const sample of samples) {
      if (!rewrites.some((rule) => ruleMatches(rule.from, sample))) {
        violations.push(
          `route ${path} is not covered by a rewrite to "/" (Pages answers ${sample} with 404)`,
        );
      }
    }
  }
  if (violations.length > 0) return violations;

  // Everything Pages would do is right; the file must also be exactly what
  // the generator writes, so ordering and spacing cannot drift unnoticed.
  let expected;
  try {
    expected = buildRedirects(manifestPaths, entries);
  } catch (error) {
    return [`_redirects cannot be generated: ${error.message}`];
  }
  const drift = firstDifference(text, expected);
  return drift === null
    ? []
    : [`_redirects ${drift}; it must be exactly what buildRedirects writes`];
}

/**
 * Every way a finished dist breaks the Pages contract, as readable messages;
 * an empty array means the dist is good. entries are the top-level names of
 * the dist, index.html and 404.html are bytes or text, and a missing file is
 * null. Without csp, the policy found in _headers is taken as given and only
 * the rest of the file is checked.
 */
export function findDemoPagesViolations({
  entries,
  manifestPaths,
  redirects,
  headers,
  indexHtml,
  notFoundHtml,
  csp,
}) {
  const violations = [];
  if (indexHtml == null) violations.push("index.html is missing");
  if (notFoundHtml == null) {
    violations.push(
      "404.html is missing, so Pages falls back to single-page-application " +
        "mode and answers every unknown path with index.html and 200",
    );
  } else if (
    indexHtml != null &&
    !Buffer.from(notFoundHtml).equals(Buffer.from(indexHtml))
  ) {
    violations.push("404.html is not a byte copy of index.html");
  }
  violations.push(...headersViolations(headers, csp));
  const manifestUsable =
    Array.isArray(manifestPaths) &&
    manifestPaths.length > 0 &&
    manifestPaths.every((path) => typeof path === "string");
  if (!manifestUsable) violations.push("route-manifest.json has no paths");
  violations.push(
    ...redirectsViolations(
      redirects,
      manifestUsable ? manifestPaths : null,
      entries,
    ),
  );
  return violations;
}

/** Read a finished dist from disk and return findDemoPagesViolations for it. */
export async function validateDemoPagesDist(distDir, { csp } = {}) {
  const readIfPresent = async (name, encoding) => {
    try {
      return await readFile(join(distDir, name), encoding);
    } catch (error) {
      if (error.code === "ENOENT") return null;
      throw error;
    }
  };
  const manifestText = await readIfPresent("route-manifest.json", "utf8");
  let manifestPaths = null;
  try {
    manifestPaths = JSON.parse(manifestText ?? "null")?.paths ?? null;
  } catch {
    manifestPaths = null;
  }
  return findDemoPagesViolations({
    entries: await readdir(distDir),
    manifestPaths,
    redirects: await readIfPresent("_redirects", "utf8"),
    headers: await readIfPresent("_headers", "utf8"),
    indexHtml: await readIfPresent("index.html"),
    notFoundHtml: await readIfPresent("404.html"),
    csp,
  });
}
